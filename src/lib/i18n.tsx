export type Key = keyof typeof en;

/** Raw dictionaries, for text that must not depend on the visitor's language (e.g. structured data). */
export const strings = { en, ar };

type I18n = {
  lang: Lang;
  isRTL: boolean;
  /** True once the saved or device language has been applied (web starts in English to match the pre-rendered page). */
  settled: boolean;
  t: (k: Key) => string;
  setLang: (l: Lang) => void;
  currency: string;
  setCurrency: (c: string) => void;
  /** pick the Arabic or English field of a record */
  pick: <T extends Record<string, unknown>>(row: T, field: string) => string;
};

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  let device: Lang = 'en';
  try {
    if (getLocales()[0]?.languageCode === 'ar') device = 'ar';
  } catch {
    device = 'en';
  }
  // The website starts in English to match its pre-rendered pages (React must hydrate the same HTML),
  // then switches to the saved or device language straight after. The apps use the device language at once.
  const [lang, setLangState] = useState<Lang>(Platform.OS === 'web' ? 'en' : device);
  const [currency, setCurrencyState] = useState('SAR');
  const [settled, setSettled] = useState(Platform.OS !== 'web');

  useEffect(() => {
    AsyncStorage.multiGet(['lang', 'currency']).then((pairs) => {
      const l = pairs[0][1];
      const c = pairs[1][1];
      if (l === 'ar' || l === 'en') setLangState(l);
      else if (device === 'ar') setLangState('ar');
      if (c) setCurrencyState(c);
    }).catch(() => device === 'ar' && setLangState('ar')).finally(() => setSettled(true));
  }, []);

  useEffect(() => {
    setErrorLanguage(lang);
    if (Platform.OS === 'web' && typeof document !== 'undefined') {
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
      document.documentElement.lang = lang;
    }
  }, [lang]);

  const value = useMemo<I18n>(() => ({
    lang,
    isRTL: lang === 'ar',
    settled,
    t: (k) => (lang === 'ar' ? ar : en)[k],
    setLang: (l) => {
      setLangState(l);
      AsyncStorage.setItem('lang', l);
      if (Platform.OS !== 'web' && I18nManager.isRTL !== (l === 'ar')) {
        I18nManager.allowRTL(true);
        I18nManager.forceRTL(l === 'ar');
        Alert.alert((l === 'ar' ? ar : en).restartForLanguage);
      }
    },
    currency,
    setCurrency: (c) => {
      setCurrencyState(c);
      AsyncStorage.setItem('currency', c);
    },
    pick: (row, field) => String(row[`${field}_${lang}`] ?? row[`${field}_en`] ?? ''),
  }), [lang, currency, settled]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
