// Builds public/intro.js: the first-visit brand intro (the Kaaba corner), as a small stand-alone script.
//
// Why stand-alone: the intro must start at first paint. Waiting for the app's JavaScript bundle (React hydration)
// meant that on phones the bundle often arrived after the dark field's safety timeout, so the intro never played.
// This file is about 30 KB, is only requested when the intro will play (app/+html.tsx decides before the first paint),
// and draws on the pre-rendered page without React.
//
// The logo's vector paths come from src/components/logo-data.ts (the brand artwork, unchanged).
// Run by `npm run build:web`; safe to run by hand: node scripts/build-intro.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/components/logo-data.ts', import.meta.url), 'utf8');
const pick = (k) => {
  const m = src.match(new RegExp(`${k}: '([^']+)'`));
  if (!m) throw new Error(`logo-data.ts: ${k} not found`);
  return m[1];
};
const PATHS = { arabic: pick('arabic'), latin: pick('latin'), arch: pick('arch') };
const LINES = [...src.matchAll(/\{ d: '([^']+)', len: ([0-9.]+) \}/g)].map((m) => ({ d: m[1], len: +m[2] }));
if (LINES.length !== 4) throw new Error(`logo-data.ts: expected 4 ARCH_LINES, found ${LINES.length}`);
const num = (k) => {
  const m = src.match(new RegExp(`export const ${k} = ([0-9.]+)`));
  if (!m) throw new Error(`logo-data.ts: ${k} not found`);
  return +m[1];
};
const LOGO_W = num('LOGO_W');
const LOGO_H = num('LOGO_H');
const LOGO_OPACITY = num('LOGO_OPACITY');

const code = String.raw`/* Al Mukarramah: first-visit brand intro (the Kaaba corner). Generated by scripts/build-intro.mjs; do not edit. */
(function () {
  var d = document, html = d.documentElement;
  var q = null;
  try { q = new URLSearchParams(location.search).get('intro'); } catch (e) { q = null; }
  if (q === '0') return;
  var forced = q !== null;
  if (!forced && html.getAttribute('data-intro') !== '1') return;
  // The page is already visible (the dark field's safety timeout passed): never start late over a page in use.
  if (!forced && window.performance && performance.now() > 4600) { html.removeAttribute('data-intro'); return; }
  var freeze = q && /^\d+(\.\d+)?$/.test(q) ? parseFloat(q) : null;

  var P = __PATHS__, LN = __LINES__, LW = __LW__, LH = __LH__, OP = __OP__, INK = '#1C1A17', IVORY = '#F7F3EC';
  var EM = { x: 708.1, y: 24.2, w: 184.1, h: 213.8, cx: 800.15, cy: 131.1, ax: 800.1, ay: 24.2 };
  var PHOTO = '/images/brand/emblem-kaaba.webp', END = 7.7;
  var DARK = 'radial-gradient(ellipse at 50% 45%, #2a241d 0%, #14110e 55%, #0c0a08 100%)';

  var lang = null;
  try { lang = (localStorage.getItem('lang') || '').replace(/"/g, ''); } catch (e) { lang = null; }
  if (lang !== 'ar' && lang !== 'en') lang = /^ar\b/i.test(navigator.language || '') ? 'ar' : 'en';
  var rtl = lang === 'ar';
  var TAG = rtl ? 'لكل بيت مسلم' : 'For every Muslim home';

  function cl(x) { return Math.min(1, Math.max(0, x)); }
  function io(x) { x = cl(x); return x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2; }
  function eo(x) { return 1 - Math.pow(1 - cl(x), 3); }
  function r(t, a, b) { return cl((t - a) / (b - a)); }
  function lockup(h) { return { gap: h * 0.2, ruleW: h * 3.3, ruleGap: h * 0.17, size: rtl ? h * 0.24 : h * 0.19, track: rtl ? 0 : 0.22 }; }
  function geometry(W, H) {
    var narrow = W < 700;
    var emH = Math.min(H * (narrow ? 0.46 : 0.56), (W * (narrow ? 0.7 : 0.5) * EM.h) / EM.w);
    var ws = emH / EM.h;
    var fs = narrow ? (W * 0.78) / LW : Math.min((W * 0.52) / LW, (H * 0.25) / LH);
    var lockH = LH * fs * 1.6;
    var cy = H * (narrow ? 0.46 : 0.47);
    return { ws: ws, tx0: W / 2 - EM.cx * ws, ty0: cy - EM.cy * ws, fs: fs, fx: W / 2 - (LW * fs) / 2, fy: cy - lockH / 2 };
  }

  function build() {
    var W = window.innerWidth, H = window.innerHeight, g = geometry(W, H), L = lockup(LH * g.fs);
    var lines = '';
    for (var i = 0; i < LN.length; i++) {
      lines += '<path id="ami-l' + i + '" d="' + LN[i].d + '" stroke-width="1.3" stroke-dasharray="' + LN[i].len + ' ' + LN[i].len + '" style="stroke-dashoffset:' + LN[i].len + '"/>';
    }
    var el = d.createElement('div');
    el.setAttribute('aria-hidden', 'true');
    el.setAttribute('data-brand-intro', '');
    el.style.cssText = 'position:fixed;inset:0;top:0;left:0;right:0;bottom:0;z-index:2147483001;overflow:hidden;transition:opacity 260ms ease;-webkit-tap-highlight-color:transparent';
    el.innerHTML =
      '<div id="ami-field" style="position:absolute;inset:0;top:0;left:0;right:0;bottom:0">' +
        '<div id="ami-dark" style="position:absolute;inset:0;top:0;left:0;right:0;bottom:0;background:' + DARK + '"></div>' +
        '<div id="ami-ivory" style="position:absolute;inset:0;top:0;left:0;right:0;bottom:0;background:' + IVORY + ';opacity:0"></div>' +
      '</div>' +
      '<svg width="100%" height="100%" viewBox="0 0 ' + W + ' ' + H + '" style="position:absolute;inset:0;top:0;left:0;overflow:visible">' +
        '<defs>' +
          '<clipPath id="ami-clip"><path d="' + P.arch + '" clip-rule="evenodd"/></clipPath>' +
          '<filter id="ami-soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="5"/></filter>' +
          '<mask id="ami-mask" maskUnits="userSpaceOnUse" x="600" y="0" width="400" height="300"><rect id="ami-rev" x="' + EM.cx + '" y="0" width="0" height="300" fill="#fff" filter="url(#ami-soft)"/></mask>' +
          '<linearGradient id="ami-sw" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#FFE9C2" stop-opacity="0"/><stop offset="0.5" stop-color="#FFE9C2" stop-opacity="0.55"/><stop offset="1" stop-color="#FFE9C2" stop-opacity="0"/></linearGradient>' +
          '<linearGradient id="ami-th" x1="0" y1="24" x2="0" y2="238" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#FFF0CF"/><stop offset="1" stop-color="#C9A260"/></linearGradient>' +
          '<filter id="ami-glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="1.6" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter>' +
          '<radialGradient id="ami-spk"><stop offset="0" stop-color="#FFF6E0"/><stop offset="0.25" stop-color="#FFD992" stop-opacity="0.8"/><stop offset="1" stop-color="#FFC66B" stop-opacity="0"/></radialGradient>' +
        '</defs>' +
        '<g id="ami-em">' +
          '<g clip-path="url(#ami-clip)">' +
            '<g id="ami-phg"><g mask="url(#ami-mask)">' +
              '<g id="ami-ph"><image href="' + PHOTO + '" x="' + EM.x + '" y="' + EM.y + '" width="' + EM.w + '" height="' + EM.h + '" preserveAspectRatio="none"/></g>' +
              '<rect id="ami-sweep" x="600" y="0" width="90" height="300" fill="url(#ami-sw)" style="mix-blend-mode:screen" transform="skewX(-14)"/>' +
            '</g></g>' +
            '<path id="ami-ink" d="' + P.arch + '" fill="' + INK + '" fill-rule="evenodd" opacity="0"/>' +
          '</g>' +
          '<g filter="url(#ami-glow)" fill="none" stroke="url(#ami-th)" stroke-linecap="round">' + lines + '</g>' +
          '<circle id="ami-spark" cx="' + EM.ax + '" cy="' + EM.ay + '" r="14" fill="url(#ami-spk)" opacity="0"/>' +
        '</g>' +
        '<g id="ami-word" opacity="0" fill="' + INK + '"><path d="' + P.arabic + '" fill-rule="evenodd"/><path d="' + P.latin + '" fill-rule="evenodd"/></g>' +
      '</svg>' +
      '<div id="ami-line" style="position:absolute;left:0;top:0;display:flex;flex-direction:column;align-items:center;transform-origin:0 0;opacity:0;will-change:transform">' +
        '<div id="ami-rule" style="width:' + L.ruleW + 'px;height:1.5px;background:linear-gradient(90deg,rgba(176,141,82,0),rgba(176,141,82,0.85) 50%,rgba(176,141,82,0));transform:scaleX(0)"></div>' +
        '<div id="ami-tag" style="margin-top:' + L.ruleGap + 'px;font-family:' + (rtl ? "ReadexPro_500Medium,'Readex Pro',Tahoma,sans-serif" : "Manrope_600SemiBold,Manrope,'Helvetica Neue',Arial,sans-serif") + ';font-weight:' + (rtl ? 500 : 600) + ';font-size:' + L.size + 'px;line-height:' + (L.size * 1.25) + 'px;letter-spacing:' + (rtl ? 0 : L.track + 'em') + ';' + (rtl ? 'direction:rtl;' : 'text-transform:uppercase;') + 'color:#7D6237;white-space:nowrap;opacity:0"></div>' +
      '</div>';
    el.querySelector('#ami-tag').textContent = TAG;
    return el;
  }

  function run() {
    var el = build();
    d.body.appendChild(el);
    var $ = function (id) { return el.querySelector('#ami-' + id); };
    var set = function (id, a, v) { var n = $(id); if (n) n.setAttribute(a, String(v)); };
    var svg = el.querySelector('svg'), lineBox = $('line'), lineRule = $('rule'), tagEl = $('tag');
    var field = $('field'), dark = $('dark'), ivory = $('ivory');
    var paths = []; for (var i = 0; i < LN.length; i++) paths.push($('l' + i));

    function render(tt) {
      var W = window.innerWidth, H = window.innerHeight;
      svg.setAttribute('viewBox', '0 0 ' + W + ' ' + H);
      var g0 = geometry(W, H);
      set('spark', 'opacity', (io(r(tt, 0.3, 0.9)) * (1 - r(tt, 1.6, 2.4))).toFixed(3));
      set('spark', 'r', (10 + 6 * Math.sin(tt * 3)).toFixed(2));
      for (var i = 0; i < LN.length; i++) {
        var p = i < 2 ? io(r(tt, 0.8, 2.4)) : io(r(tt, 1.1, 2.6));
        if (paths[i]) { paths[i].style.strokeDashoffset = String(LN[i].len * (1 - p)); paths[i].style.opacity = String(1 - r(tt, 3.4, 4.2)); }
      }
      var w = 110 * eo(r(tt, 2.0, 3.7));
      set('rev', 'x', (EM.cx - w).toFixed(2));
      set('rev', 'width', (2 * w).toFixed(2));
      var k = 1.1 - 0.1 * io(r(tt, 2.0, 5.2));
      set('ph', 'transform', 'translate(' + (EM.ax * (1 - k)).toFixed(2) + ' ' + (EM.ay * (1 - k)).toFixed(2) + ') scale(' + k.toFixed(4) + ')');
      set('sweep', 'x', (640 + 300 * io(r(tt, 3.3, 4.8))).toFixed(1));
      set('phg', 'opacity', (1 - r(tt, 6.05, 6.4)).toFixed(3));
      var mv = io(r(tt, 4.8, 5.9));
      var S = g0.ws + (g0.fs - g0.ws) * mv, X = g0.tx0 + (g0.fx - g0.tx0) * mv, Y = g0.ty0 + (g0.fy - g0.ty0) * mv;
      var gl = io(r(tt, 6.8, 7.6));
      var slot = d.querySelector('[data-brandslot]');
      var sr = slot ? slot.getBoundingClientRect() : null;
      var hasSlot = !!sr && sr.width > 0 && sr.bottom > 0;
      if (gl > 0 && hasSlot) {
        var Sh = sr.height / LH;
        S = g0.fs + (Sh - g0.fs) * gl; X = g0.fx + (sr.left - g0.fx) * gl; Y = g0.fy + (sr.top - g0.fy) * gl;
      }
      var tr = 'translate(' + X.toFixed(2) + ' ' + Y.toFixed(2) + ') scale(' + S.toFixed(5) + ')';
      set('em', 'transform', tr);
      set('word', 'transform', tr);
      set('ink', 'opacity', (OP * io(r(tt, 5.5, 6.2))).toFixed(3));
      set('word', 'opacity', (OP * io(r(tt, 5.8, 6.6))).toFixed(3));
      var hasLine = !!d.querySelector('[data-brandline]') && hasSlot;
      var f = S / g0.fs, gap = LH * g0.fs * 0.2;
      lineBox.style.transform = 'translate(' + (X + (LW * S) / 2).toFixed(2) + 'px,' + (Y + LH * S + gap * f).toFixed(2) + 'px) scale(' + f.toFixed(5) + ') translateX(-50%)';
      lineBox.style.opacity = String(io(r(tt, 6.0, 6.5)) * (hasLine ? 1 : 1 - r(tt, 6.8, 7.15)));
      lineRule.style.transform = 'scaleX(' + eo(r(tt, 6.0, 6.6)).toFixed(4) + ')';
      lineRule.style.height = ((1.5 - 0.5 * gl) / f).toFixed(3) + 'px';
      tagEl.style.opacity = String(io(r(tt, 6.2, 6.8)));
      var qv = io(r(tt, 4.5, 5.5));
      dark.style.opacity = qv >= 1 ? '0' : '1';
      ivory.style.opacity = qv > 0 ? '1' : '0';
      var R = qv * Math.hypot(W, H) * 1.05, ex = X + EM.cx * S, ey = Y + EM.cy * S;
      var mk = qv >= 1 ? 'none' : 'radial-gradient(circle at ' + ex.toFixed(1) + 'px ' + ey.toFixed(1) + 'px, #000 ' + R.toFixed(1) + 'px, transparent ' + (R + 380).toFixed(1) + 'px)';
      ivory.style.maskImage = mk; ivory.style.webkitMaskImage = mk;
      field.style.opacity = String(hasSlot ? 1 - io(r(tt, 6.85, 7.6)) : 1 - io(r(tt, 6.9, 7.6)));
      if (!hasSlot) el.style.opacity = String(1 - io(r(tt, 7.1, 7.7)));
    }

    // our own dark field is on screen: the pre-paint cover (CSS) can go; the header's logo stays hidden until we land
    html.setAttribute('data-intro', 'live');

    if (freeze !== null) {
      var draw = function () { render(freeze); };
      draw(); setTimeout(draw, 400); window.addEventListener('resize', draw);
      return;
    }

    var raf = 0, done = false;
    function off() {
      window.removeEventListener('pointerdown', skip, true);
      window.removeEventListener('keydown', skip, true);
      window.removeEventListener('wheel', skip, true);
      window.removeEventListener('touchstart', skip, true);
    }
    function finish(skipped) {
      if (done) return;
      done = true;
      cancelAnimationFrame(raf);
      off();
      var end = function () { html.removeAttribute('data-intro'); if (el.parentNode) el.parentNode.removeChild(el); };
      if (skipped) { el.style.opacity = '0'; el.style.pointerEvents = 'none'; setTimeout(end, 280); } else end();
    }
    function skip() { finish(true); }
    var now = window.performance ? performance.now() : 0;
    var t0 = Math.min(0.3, Math.max(0, now / 1000 - 0.4));
    var start = now - t0 * 1000;
    function tick(ts) {
      var tt = ((window.performance ? performance.now() : ts) - start) / 1000;
      render(tt);
      if (tt >= END) finish(false); else raf = requestAnimationFrame(tick);
    }
    render(t0);
    raf = requestAnimationFrame(tick);
    window.addEventListener('pointerdown', skip, true);
    window.addEventListener('keydown', skip, true);
    window.addEventListener('wheel', skip, { passive: true, capture: true });
    window.addEventListener('touchstart', skip, { passive: true, capture: true });
  }

  function whenBody() {
    if (d.body) { try { run(); } catch (e) { html.removeAttribute('data-intro'); } }
    else requestAnimationFrame(whenBody);
  }
  whenBody();
})();
`;

const out = code
  .replace('__PATHS__', JSON.stringify(PATHS))
  .replace('__LINES__', JSON.stringify(LINES))
  .replace('__LW__', String(LOGO_W))
  .replace('__LH__', String(LOGO_H))
  .replace('__OP__', String(LOGO_OPACITY));
writeFileSync(new URL('../public/intro.js', import.meta.url), out);
console.log(`public/intro.js written (${(out.length / 1024).toFixed(1)} KB)`);
